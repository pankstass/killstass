#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
# Host flock prevents two backups, including timer/manual overlap.
BACKUP_DIR=${BACKUP_DIR:-/var/backups/killstass}
KEEP_BACKUPS=${KEEP_BACKUPS:-14}
case "$KEEP_BACKUPS" in ''|*[!0-9]*) echo 'KEEP_BACKUPS must be integer' >&2; exit 1;; esac
[ "$KEEP_BACKUPS" -ge 1 ]
umask 077
mkdir -p "$BACKUP_DIR"
exec 9>"$BACKUP_DIR/.backup.lock"
flock -n 9 || exit 0
stamp=$(date -u +%Y%m%dT%H%M%SZ)
file="$BACKUP_DIR/killstass-$stamp.dump"
trap 'rm -f "$file.tmp"' EXIT HUP INT TERM
docker compose exec -T db sh -c 'exec pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" -Fc -Z 3 --no-owner --no-acl' > "$file.tmp"
[ -s "$file.tmp" ]
# Verify archive directory before atomically publishing.
docker compose exec -T db pg_restore --list < "$file.tmp" >/dev/null
mv "$file.tmp" "$file"
# Filenames are generated by this script, no arbitrary path or whitespace.
ls -1 "$BACKUP_DIR"/killstass-*.dump | sort -r | tail -n +$((KEEP_BACKUPS+1)) | while IFS= read -r old; do rm -- "$old"; done
printf '%s\n' "$file"
