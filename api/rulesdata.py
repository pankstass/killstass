"""v1.11: general Kill Team rules for the reference (operator tool, stdlib only).

    python -m api.rulesdata fetch [--ref TAG] > rules.json     (needs internet; ORACLE_REF, default: latest release)
    python -m api.rulesdata sql < rules.json | psql -U killstass_owner ...   (production: owner role)
    python -m api.rulesdata load < rules.json                  (dev/tests: owner DATABASE_URL)
    python -m api.rulesdata export > rules.json                (the rules now in the database: backups, rollback)
    python -m api.rulesdata status                             (read-only)

Source: warhammer-oracle https://github.com/gregario/warhammer-oracle (MIT). Only its rules data is used, and it is
read as data — the oracle's code is never run (no npm, no Node):
  * src/data/kill-team-rules.ts  KILL_TEAM_SHARED_RULES — weapon rules generated by the oracle from
    BSData/wh40k-killteam ("2024 - Kill Team.gst", shared rules); verification 'bsdata';
  * src/data/phases.ts           PHASES_KILL_TEAM — phase overview written by the oracle authors; 'unverified'.
Teams, operatives, ploys and equipment keep coming from BSData and kt-datacards (api/teamdata.py), Tac Ops and
missions from the KILLSTASS catalog. Russian paraphrases (api/data/weapon-rules-ru.json) are editorial; one is used
only while the English text it was written for is unchanged (sha256 "basis"). The same file lists other Russian names
in use ("aliases": transliterations such as «летал», other translations) for the search.
"""
import hashlib, json, os, re, sys
from datetime import datetime, timezone
from . import teamdata as td

FORMAT = 'killstass-rules/1'
ORACLE = 'gregario/warhammer-oracle'
FILES = {'rules': 'src/data/kill-team-rules.ts', 'phases': 'src/data/phases.ts'}
RU_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data', 'weapon-rules-ru.json')
MAX_BUNDLE = 2 * 1024 * 1024
CODE = re.compile(r'^(weapon|phase)-[a-z0-9-]{1,60}$')
SHA = re.compile(r'^[0-9a-f]{40}$')

# ---------------------------------------------------------------- TypeScript data files
def _skip(s, i):
    """Whitespace and // or /* */ comments."""
    while i < len(s):
        if s[i].isspace(): i += 1
        elif s.startswith('//', i): i = s.find('\n', i) + 1 or len(s)
        elif s.startswith('/*', i):
            j = s.find('*/', i + 2)
            if j < 0: raise ValueError('unterminated comment')
            i = j + 2
        else: break
    return i

ESC = {'n': '\n', 't': '\t', 'r': '\r', 'b': '\b', 'f': '\f', 'v': '\v', '0': '\0'}
def _string(s, i):
    q, i, out = s[i], i + 1, []
    while i < len(s):
        c = s[i]
        if c == q: return ''.join(out), i + 1
        if c == '\\':
            n = s[i + 1]
            if n == 'u':
                out.append(chr(int(s[i + 2:i + 6], 16))); i += 6; continue
            out.append(ESC.get(n, n)); i += 2; continue
        if c == '\n': raise ValueError('newline in string')
        out.append(c); i += 1
    raise ValueError('unterminated string')

def literal(s, i=0, depth=0):
    """A JSON-like TypeScript literal (objects, arrays, strings, numbers, true/false/null; bare keys and trailing
    commas allowed) -> (value, end). Anything else (template strings, spreads, calls, identifiers) is refused."""
    if depth > 20: raise ValueError('nesting too deep')
    i = _skip(s, i)
    if i >= len(s): raise ValueError('unexpected end')
    c = s[i]
    if c in '"\'': return _string(s, i)
    if c in '[{':
        close, out = (']', []) if c == '[' else ('}', {})
        i += 1
        while True:
            i = _skip(s, i)
            if i < len(s) and s[i] == close: return out, i + 1
            if c == '[':
                v, i = literal(s, i, depth + 1); out.append(v)
            else:
                if s[i] in '"\'': k, i = _string(s, i)
                else:
                    m = re.compile(r'[A-Za-z_$][\w$]*').match(s, i)
                    if not m: raise ValueError(f'bad key at {i}')
                    k, i = m.group(0), m.end()
                i = _skip(s, i)
                if s[i] != ':': raise ValueError(f'":" expected at {i}')
                v, i = literal(s, i + 1, depth + 1); out[k] = v
            i = _skip(s, i)
            if i < len(s) and s[i] == ',': i += 1
            elif i < len(s) and s[i] == close: return out, i + 1
            else: raise ValueError(f'"," or "{close}" expected at {i}')
    m = re.compile(r'-?\d+(\.\d+)?').match(s, i)
    if m: return (float(m.group(0)) if m.group(1) else int(m.group(0))), m.end()
    for word, v in (('true', True), ('false', False), ('null', None)):
        if s.startswith(word, i) and not re.match(r'[\w$]', s[i + len(word):i + len(word) + 1]): return v, i + len(word)
    raise ValueError(f'unsupported value at {i}')

def _const(text, name):
    m = re.search(r'\bconst\s+' + name + r'\b[^=]*=', text)
    if not m: raise ValueError(f'{name} not found')
    return literal(text, m.end())[0]

def _clean(v, limit):
    v = re.sub(r'[ \t]+', ' ', str(v).replace('\r', '')).strip()
    if not 1 <= len(v) <= limit: raise ValueError('empty or too long text')
    return v

def parse_rules(text):
    """kill-team-rules.ts -> ([{name, description}], generated_at, upstream source URL)."""
    items = _const(text, 'KILL_TEAM_SHARED_RULES')
    if not isinstance(items, list) or not 5 <= len(items) <= 200: raise ValueError('KILL_TEAM_SHARED_RULES: 5..200 rules expected')
    out, seen = [], set()
    for r in items:
        if not isinstance(r, dict): raise ValueError('rule must be an object')
        name, desc = _clean(r.get('name', ''), 80), _clean(r.get('description', ''), 4000)
        if name.lower() in seen: raise ValueError(f'duplicate rule {name}')
        seen.add(name.lower()); out.append({'name': name, 'description': desc})
    gen = re.search(r'^//\s*Generated:\s*(\S+)', text, re.M)
    src = re.search(r'^//\s*Source:\s*(https://\S+)', text, re.M)
    return out, gen and gen.group(1), src and src.group(1)

def parse_phases(text):
    """phases.ts -> Kill Team phases [{name, order, steps, tips}]."""
    items = _const(text, 'PHASES_KILL_TEAM')
    if not isinstance(items, list) or not 1 <= len(items) <= 12: raise ValueError('PHASES_KILL_TEAM: 1..12 phases expected')
    out = []
    for p in items:
        if not isinstance(p, dict) or p.get('gameMode', 'kill_team') != 'kill_team': raise ValueError('not a Kill Team phase')
        steps, tips = p.get('steps', []), p.get('tips', [])
        if not isinstance(steps, list) or not isinstance(tips, list) or not steps: raise ValueError('phase steps expected')
        out.append({'name': _clean(p.get('name', ''), 80), 'order': int(p.get('order', len(out) + 1)),
                    'steps': [_clean(x, 1500) for x in steps][:30], 'tips': [_clean(x, 1500) for x in tips][:30]})
    return sorted(out, key=lambda p: p['order'])

# ---------------------------------------------------------------- fetch
def _version(tag): return tuple(int(x) for x in re.findall(r'\d+', tag))

def latest_tag():
    try:
        tag = td.gh_json(f'repos/{ORACLE}/releases/latest').get('tag_name')
        if tag: return tag
    except Exception:  # no GitHub releases: fall back to the highest version tag
        pass
    tags = [t['name'] for t in td.gh_json(f'repos/{ORACLE}/tags?per_page=100') if re.fullmatch(r'v?\d+(\.\d+){1,3}', t.get('name', ''))]
    if not tags: raise RuntimeError('warhammer-oracle: no release tags')
    return max(tags, key=_version)

def build(files, tag, commit, log=sys.stderr):
    """files: {'rules': text, 'phases': text or None} -> bundle (also used by the tests with fixture texts)."""
    warnings = []
    digest = {k: hashlib.sha256(v.encode()).hexdigest() for k, v in files.items() if v is not None}
    rules, generated, upstream = parse_rules(files['rules'])
    base = {'repo': ORACLE, 'tag': tag, 'commit': commit}
    rsrc = {**base, 'path': FILES['rules'], 'sha256': digest['rules'], 'generated_at': generated, 'upstream': upstream}
    entries, codes = [], set()
    for i, r in enumerate(rules):
        code = 'weapon-' + td.slugify(r['name'])[:60]
        if not CODE.match(code) or code in codes: raise ValueError(f'bad or duplicate rule code {code}')
        codes.add(code)
        entries.append({'code': code, 'kind': 'weapon_rule', 'name': r['name'], 'text_en': r['description'], 'details': {},
                        'verification': 'bsdata', 'sort': i, 'source': rsrc})
    phases = []
    if files.get('phases') is not None:
        try: phases = parse_phases(files['phases'])
        except ValueError as e: warnings.append(f'phases skipped: {e}')
    psrc = {**base, 'path': FILES['phases'], 'sha256': digest.get('phases')}
    for p in phases:
        code = 'phase-' + td.slugify(p['name'])[:60]
        if not CODE.match(code) or code in codes: raise ValueError(f'bad or duplicate phase code {code}')
        codes.add(code)
        entries.append({'code': code, 'kind': 'phase', 'name': p['name'], 'text_en': '\n'.join('• ' + s for s in p['steps']),
                        'details': {'order': p['order'], 'steps': p['steps'], 'tips': p['tips']},
                        'verification': 'unverified', 'sort': p['order'], 'source': psrc})
    for w in warnings: print('warning:', w, file=log)
    return {'format': FORMAT, 'built_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
            'sources': {'oracle': {**base, 'license': 'MIT', 'files': {'rules': rsrc, 'phases': psrc if phases else None}}},
            'entries': entries, 'warnings': warnings}

def fetch(ref=None, log=sys.stderr):
    tag = ref or latest_tag()
    commit = td.gh_json(f'repos/{ORACLE}/commits/{tag}')['sha']
    print(f'warhammer-oracle {tag} ({commit[:10]})', file=log)
    files = {'rules': td.http(td.raw(ORACLE, commit, FILES['rules'])).decode('utf-8')}
    try: files['phases'] = td.http(td.raw(ORACLE, commit, FILES['phases'])).decode('utf-8')
    except RuntimeError as e:
        print('warning: phases not downloaded:', e, file=log); files['phases'] = None
    return build(files, tag, commit, log)

# ---------------------------------------------------------------- load
def validate(bundle, allow_empty=False):
    if not isinstance(bundle, dict) or bundle.get('format') != FORMAT: raise ValueError('not a killstass rules bundle')
    entries = bundle.get('entries')
    if not isinstance(entries, list) or not (0 if allow_empty else 1) <= len(entries) <= 300: raise ValueError('bundle must contain 1..300 rules')
    seen = set()
    for e in entries:
        if not isinstance(e, dict) or not CODE.match(str(e.get('code', ''))): raise ValueError(f'bad rule code {e.get("code") if isinstance(e, dict) else e!r}')
        if e['code'] in seen: raise ValueError(f'duplicate rule code {e["code"]}')
        seen.add(e['code'])
        if e.get('kind') not in ('weapon_rule', 'phase') or not e['code'].startswith('weapon-' if e['kind'] == 'weapon_rule' else 'phase-'):
            raise ValueError(f'{e["code"]}: bad kind')
        if not 1 <= len(str(e.get('name', ''))) <= 120 or not 1 <= len(str(e.get('text_en', ''))) <= 8000: raise ValueError(f'{e["code"]}: bad text')
        if e.get('verification') not in ('bsdata', 'unverified') or not isinstance(e.get('details', {}), dict): raise ValueError(f'{e["code"]}: bad fields')
        src = e.get('source')
        if not isinstance(src, dict) or src.get('repo') != ORACLE or not SHA.match(str(src.get('commit', ''))): raise ValueError(f'{e["code"]}: provenance required')
    return entries

def russian():
    try:
        with open(RU_FILE, encoding='utf-8') as f: return json.load(f).get('rules', {})
    except FileNotFoundError: return {}

def text_hash(t): return hashlib.sha256(str(t).strip().encode()).hexdigest()

def rows(bundle, allow_empty=False):
    """Bundle entries + current Russian paraphrases -> table rows and warnings."""
    ru, out, warnings = russian(), [], []
    for e in validate(bundle, allow_empty):
        r = ru.get(e['code']) or {}
        fresh = r.get('basis') == text_hash(e['text_en'])
        if r and not fresh: warnings.append(f'{e["code"]}: English text changed, the Russian paraphrase is hidden until reviewed')
        aliases = r.get('aliases') if isinstance(r.get('aliases'), list) else []
        row = {'code': e['code'], 'kind': e['kind'], 'name': str(e['name']), 'name_ru': str(r.get('name_ru', '')),
               'aliases': [a.strip() for a in aliases if isinstance(a, str) and 0 < len(a.strip()) <= 60][:12],
               'text_en': str(e['text_en']), 'text_ru': str(r.get('text_ru', '')) if fresh else '', 'details': e.get('details') or {},
               'verification': e['verification'], 'source': e['source'], 'sort': int(e.get('sort') or 0)}
        row['content_hash'] = hashlib.sha256(json.dumps({k: row[k] for k in ('kind', 'name', 'name_ru', 'aliases', 'text_en', 'text_ru', 'details', 'verification')},
                                                        ensure_ascii=False, sort_keys=True).encode()).hexdigest()
        out.append(row)
    return out, warnings

def to_sql(bundle, allow_empty=False):
    """Bundle -> one SQL script run by the database OWNER (the app role can only read rule_entries)."""
    entries, warnings = rows(bundle, allow_empty)
    warnings = (bundle.get('warnings') or [])[:200] + warnings
    lit = td.lit
    out = ['SET LOCAL standard_conforming_strings = on;', 'SET LOCAL client_min_messages = warning;']
    if entries:
        out.append(f"""INSERT INTO rule_entries(code,kind,name,name_ru,aliases,text_en,text_ru,details,verification,source,sort,active,content_hash,imported_at)
SELECT x->>'code',x->>'kind',x->>'name',x->>'name_ru',ARRAY(SELECT jsonb_array_elements_text(x->'aliases')),x->>'text_en',x->>'text_ru',x->'details',
x->>'verification',x->'source',(x->>'sort')::int,true,x->>'content_hash',now()
FROM jsonb_array_elements({lit(json.dumps(entries, ensure_ascii=False, sort_keys=True))}::jsonb) x
ON CONFLICT(code) DO UPDATE SET kind=excluded.kind,name=excluded.name,name_ru=excluded.name_ru,aliases=excluded.aliases,text_en=excluded.text_en,text_ru=excluded.text_ru,
details=excluded.details,verification=excluded.verification,source=excluded.source,sort=excluded.sort,active=true,content_hash=excluded.content_hash,
imported_at=CASE WHEN rule_entries.active AND rule_entries.content_hash=excluded.content_hash THEN rule_entries.imported_at ELSE now() END;""")
    counts = {k: sum(e['kind'] == k for e in entries) for k in ('weapon_rule', 'phase')}
    for kind, n in counts.items():
        codes = ','.join(lit(e['code']) for e in entries if e['kind'] == kind)
        if n: out.append(f"UPDATE rule_entries SET active=false WHERE kind='{kind}' AND active AND code NOT IN ({codes});")
        elif allow_empty or kind == 'weapon_rule': out.append(f"UPDATE rule_entries SET active=false WHERE kind='{kind}' AND active;")
        else: warnings.append('no phases in the bundle: the current phase overview is kept')
    built = bundle.get('built_at')
    out.append('INSERT INTO rule_imports(built_at,sources,rules,phases,warnings) VALUES('
               f"{lit(built) + '::timestamptz' if built else 'NULL'},{lit(json.dumps(bundle.get('sources', {}), ensure_ascii=False))}::jsonb,"
               f"{counts['weapon_rule']},{counts['phase']},{lit(json.dumps(warnings[:500], ensure_ascii=False))}::jsonb);")
    out.append(td.REFRESH_SQL)
    out.append("SELECT format('rules: %s, phases: %s, warnings: %s', rules, phases, jsonb_array_length(warnings)) FROM rule_imports ORDER BY id DESC LIMIT 1;")
    return '\n'.join(out) + '\n'

def load(bundle, conn, allow_empty=False):
    """Development/tests: run the same script on an owner connection."""
    sql = to_sql(bundle, allow_empty)
    with conn.transaction():
        conn.execute(sql)
    r = conn.execute('SELECT rules, phases, warnings FROM rule_imports ORDER BY id DESC LIMIT 1').fetchone()
    return {'rules': r[0], 'phases': r[1], 'warnings': r[2]}

def export(conn):
    """Active rules as a bundle (same format as fetch) for backups and scripts/update-reference.sh --rollback."""
    imp = conn.execute('SELECT built_at, sources FROM rule_imports ORDER BY id DESC LIMIT 1').fetchone()
    cur = conn.execute('SELECT code,kind,name,text_en,details,verification,source,sort,content_hash FROM rule_entries WHERE active ORDER BY kind DESC,sort,code')
    keys = [d.name for d in cur.description]
    return {'format': FORMAT, 'built_at': imp[0].isoformat() if imp and imp[0] else None, 'sources': imp[1] if imp else {},
            'exported_at': datetime.now(timezone.utc).isoformat(timespec='seconds'), 'warnings': [],
            'entries': [dict(zip(keys, r)) for r in cur.fetchall()]}

def read_bundle(stream):
    data = stream.read(MAX_BUNDLE + 1)
    if len(data) > MAX_BUNDLE: raise SystemExit('bundle too large')
    return json.loads(data)

def main(argv):
    cmd = argv[1] if len(argv) > 1 else ''
    opt = lambda k, d: argv[argv.index(k) + 1] if k in argv else d
    if cmd == 'fetch':
        json.dump(fetch(opt('--ref', os.getenv('ORACLE_REF') or None)), sys.stdout, ensure_ascii=False)
        return 0
    if cmd == 'sql':
        sys.stdout.write(to_sql(read_bundle(sys.stdin.buffer)))
        return 0
    if cmd in ('load', 'status', 'export'):
        import psycopg
        with psycopg.connect(os.environ['DATABASE_URL']) as conn:
            if cmd == 'load': print(json.dumps(load(read_bundle(sys.stdin.buffer), conn), ensure_ascii=False))
            elif cmd == 'export': json.dump(export(conn), sys.stdout, ensure_ascii=False)
            else:
                r = conn.execute('SELECT imported_at, rules, phases, sources FROM rule_imports ORDER BY id DESC LIMIT 1').fetchone()
                o = (r[3] or {}).get('oracle', {}) if r else {}
                print('no import yet' if not r else f'{r[0]:%Y-%m-%d %H:%M} UTC: {r[1]} weapon rules, {r[2]} phases, '
                      f'warhammer-oracle {o.get("tag")} @{str(o.get("commit"))[:10]}')
        return 0
    print(__doc__, file=sys.stderr); return 2

if __name__ == '__main__':
    sys.exit(main(sys.argv))
